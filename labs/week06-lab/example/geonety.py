def calculate_triangle_area(Hight, base):
    """Calculates and displays triangle area"""
    area = Hight * base
    print(f"Triangle with Hight {Hight} and base {base}")
    print(f"Area = 0.5 * {Hight} × {base} = {area}")
    print()
 
